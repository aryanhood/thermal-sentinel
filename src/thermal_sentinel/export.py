"""Export deterministic JSON consumed by the static web dashboard."""

from __future__ import annotations

import json
from dataclasses import asdict
from pathlib import Path
from typing import Any

from . import __version__
from .benchmark import FAULT_CHOICES, run_benchmark
from .model import make_scenario
from .simulation import PolicyConfig, run_pair

__all__ = ["DEMO_SEEDS", "check_export", "export", "render_benchmark_markdown"]

DEMO_SEEDS: tuple[int, ...] = (1, 2, 3, 4, 5, 6)
DATA_DIR = Path("web/public/data")
BENCHMARK_DOC = Path("docs/benchmark.md")


def _dump(data: Any) -> str:
    return json.dumps(data, sort_keys=True, separators=(",", ":"), ensure_ascii=False, allow_nan=False) + "\n"


def build_files() -> dict[str, str]:
    """Return every generated file as ``path relative to the repo root -> text``."""
    files: dict[str, str] = {}
    config = PolicyConfig()
    catalog: list[dict[str, Any]] = []
    for seed in DEMO_SEEDS:
        for bay in FAULT_CHOICES:
            scenario = make_scenario(seed, bay)
            pair = run_pair(scenario, config)
            document = {
                "case_id": scenario.case_id,
                "scenario": asdict(scenario),
                "config": asdict(config),
                "time_saved_s": pair.time_saved_s,
                "fixed": pair.fixed.to_dict(),
                "adaptive": pair.adaptive.to_dict(),
            }
            files[(DATA_DIR / "scenarios" / f"{scenario.case_id}.json").as_posix()] = _dump(document)
            catalog.append(
                {
                    "case_id": scenario.case_id,
                    "seed": seed,
                    "fault_bay": bay,
                    "fault_onset_s": scenario.fault_onset_s,
                    "time_saved_s": pair.time_saved_s,
                }
            )
    report = run_benchmark(config=config)
    files[(DATA_DIR / "index.json").as_posix()] = _dump({"version": __version__, "scenarios": catalog})
    files[(DATA_DIR / "benchmark.json").as_posix()] = _dump(report.data)
    files[BENCHMARK_DOC.as_posix()] = render_benchmark_markdown(report.data)
    return files


def export(root: Path) -> list[Path]:
    """Write all generated files below the repository ``root``."""
    written: list[Path] = []
    files = build_files()
    for relative, text in files.items():
        path = root / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")
        written.append(path)
    for path in (root / DATA_DIR / "scenarios").glob("*.json"):
        if (DATA_DIR / "scenarios" / path.name).as_posix() not in files:
            path.unlink()
    return written


def check_export(root: Path) -> list[str]:
    """Return generated paths that are missing, stale, or unexpected."""
    problems: list[str] = []
    expected = build_files()
    for relative, text in expected.items():
        path = root / relative
        if not path.is_file() or path.read_bytes().decode("utf-8") != text:
            problems.append(relative)
    scenario_dir = root / DATA_DIR / "scenarios"
    if scenario_dir.is_dir():
        for path in sorted(scenario_dir.glob("*.json")):
            relative = (DATA_DIR / "scenarios" / path.name).as_posix()
            if relative not in expected:
                problems.append(f"{relative} (unexpected)")
    return problems


def _fmt(value: Any, suffix: str = "") -> str:
    return "—" if value is None else f"{value}{suffix}"


def render_benchmark_markdown(report: dict[str, Any]) -> str:
    s = report["summary"]
    f, a, p = s["fixed"], s["adaptive"], s["paired"]
    ci = p["time_saved_ci95_s"]
    o = p["outcomes"]
    lines = [
        "# Benchmark results",
        "",
        "<!-- Generated by `thermal-sentinel export`. Do not edit by hand. -->",
        "",
        f"{s['cases']} paired scenarios ({s['fault_cases']} with an injected fault, "
        f"{s['no_fault_cases']} fault-free controls), {s['simulated_hours']} simulated hours per policy.",
        "",
        "| Metric | Fixed patrol | Risk-adaptive |",
        "|---|---:|---:|",
        f"| Detection rate | {_fmt(f['detection_rate_pct'], '%')} | {_fmt(a['detection_rate_pct'], '%')} |",
        (
            f"| Time to confirm, median | {_fmt(f['time_to_confirm_s']['median'], ' s')} "
            f"| {_fmt(a['time_to_confirm_s']['median'], ' s')} |"
        ),
        (
            f"| Time to confirm, p90 | {_fmt(f['time_to_confirm_s']['p90'], ' s')} "
            f"| {_fmt(a['time_to_confirm_s']['p90'], ' s')} |"
        ),
        (
            f"| Distance per mission, mean | {_fmt(f['distance_m']['mean'], ' m')} "
            f"| {_fmt(a['distance_m']['mean'], ' m')} |"
        ),
        f"| False alarms per hour | {_fmt(f['false_alarms_per_hour'])} | {_fmt(a['false_alarms_per_hour'])} |",
        f"| Worst coverage gap | {_fmt(f['max_unseen_s']['max'], ' s')} | {_fmt(a['max_unseen_s']['max'], ' s')} |",
        f"| Coverage guardrail met | {_fmt(f['guardrail_ok_pct'], '%')} | {_fmt(a['guardrail_ok_pct'], '%')} |",
        "",
        "## Paired comparison",
        "",
        f"- Mean time saved: **{_fmt(p['time_saved_s']['mean'], ' s')}**"
        + (f" (95% bootstrap CI {ci[0]} – {ci[1]} s)" if ci else ""),
        f"- Outcomes on fault cases: adaptive faster {o['adaptive_faster']}, tie {o['tie']}, "
        f"fixed faster {o['fixed_faster']}, only-adaptive {o['adaptive_only']}, only-fixed {o['fixed_only']}, "
        f"neither {o['neither']}",
        f"- Distance overhead of adaptive: mean {_fmt(p['distance_overhead_pct']['mean'], '%')}, "
        f"p90 {_fmt(p['distance_overhead_pct']['p90'], '%')}",
        "",
        "## What this costs",
        "",
        "The adaptive policy trusts line telemetry, so transient sensor glitches send it on detours that",
        "the fixed patrol never makes. Those appear above as false alarms per hour, extra distance, and a",
        "larger worst-case coverage gap, which stays inside the guardrail.",
        "",
        "## Method",
        "",
        f"- Seeds {report['method']['seeds'][0]}–{report['method']['seeds'][1]}; "
        f"fault bay ∈ {{{', '.join(report['method']['fault_choices'])}}}",
        f"- Fault onset: {report['method']['fault_onset']}; horizon {report['method']['horizon_s']} s",
        f"- Pairing: {report['method']['pairing']}",
        "",
    ]
    return "\n".join(lines)
